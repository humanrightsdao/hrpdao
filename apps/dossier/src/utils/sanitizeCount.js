// src/utils/sanitizeCount.js
//
// ДОДАНО: захист від зіпсованих лічильників з Lens API/індексатора.
//
// Виявлений баг: Lens зберігає stats.upvotes/downvotes як беззнаковий
// 64-бітний лічильник на своєму боці. Виклик undoReaction() на реакції,
// якої фактично не існує (наприклад, через баг з localStorage, який ми
// вже виправили на клієнті — див. useLensPosts.js/CountryFeed.jsx),
// сервер обробляє як банальне "відняти 1" БЕЗ перевірки на нуль. Якщо
// лічильник уже був 0, відняти 1 в межах u64-арифметики — це не -1, а
// переповнення в максимальне значення: 18446744073709551615 (те саме,
// що дає BigInt.asUintN(64, -1n)), яке JS Number округлює до
// 18446744073709552000 — саме це число й побачив користувач одразу на
// "Правда", і на "Неправда" для того самого поста.
//
// Це пошкодження даних на боці самого Lens-індексатора: ми не можемо
// виправити вже збережене там значення з фронтенду. Наші попередні
// фікси (my_reaction тепер береться з operations.hasUpvoted/hasDownvoted,
// а не з localStorage) запобігають НОВИМ випадкам цього багу — але старі
// пошкоджені пости так і повертатимуть це сире число з API назавжди,
// доки хтось не втрутиться на рівні протоколу.
//
// sanitizeCount() — це суто захист на рівні відображення: будь-яке
// значення, яке явно не може бути реальною кількістю реакцій/лайків
// (від'ємне, чи ближче до меж 64-бітного цілого, ніж до будь-якого
// правдоподібного людського числа), показуємо як 0 замість сирого
// сміття з API.
const SANITY_CEILING = 1_000_000_000; // з великим запасом понад будь-яку реалістичну кількість реакцій

export const sanitizeCount = (value) => {
  const n = Number(value);
  if (!Number.isFinite(n) || n < 0 || n > SANITY_CEILING) return 0;
  return n;
};
